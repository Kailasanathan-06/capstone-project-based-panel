"""
Task Manager
============
Holds tasks in memory, provides validation/cleaning, generates synthetic task
records and streams paginated results to the frontend. Uses pandas/numpy for
efficient processing of large datasets.
"""

import os
import random
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import numpy as np
import pandas as pd

import config


class TaskManager:
    """In-memory store for task records plus generation/validation logic."""

    def __init__(self, seed=None):
        self.rng = random.Random(seed or config.DATASET_SEED)
        self.tasks = None  # DataFrame
        self.results = {}  # task_id -> dict(resource, latency, energy)
        self.analytics = {}
        self.cleaning_stats = {}
        self._generation_progress = 0.0
        self._processing_progress = 0.0

    def reset(self):
        self.tasks = None
        self.results = {}
        self.analytics = {}
        self.cleaning_stats = {}
        self._generation_progress = 0.0
        self._processing_progress = 0.0

    # ------------------------------------------------------------------
    # Generation
    # ------------------------------------------------------------------
    def generate(self, n):
        """Generate a synthetic task dataset with a fixed seed."""
        n = int(n)
        self._generation_progress = 0.0
        rng = np.random.default_rng(config.DATASET_SEED)

        task_types = config.TASK_TYPES
        n_types = len(task_types)

        data = {
            "task_id": [f"T{10000+i:06d}" for i in range(n)],
            "timestamp": pd.date_range("2026-01-01", periods=n, freq="4ms"),
            "task_type": [task_types[i] for i in (rng.integers(0, n_types, n))],
            "data_size_mb": np.round(rng.uniform(0.2, 22.0, n), 2),
            "cpu_cycles_giga": np.round(rng.uniform(0.1, 5.0, n), 2),
            "memory_mb": np.round(rng.uniform(32, 1024, n), 0),
            "deadline_ms": np.round(rng.uniform(90, 900, n), 0),
            "privacy_sensitivity": np.round(rng.uniform(0.05, 1.0, n), 3),
            "security_sensitivity": np.round(rng.uniform(0.05, 1.0, n), 3),
            "arrival_rate": np.round(rng.uniform(1, 40, n), 2),
            "source_node": np.random.choice(["EDGE"], n),
            "preferred_resource": np.random.choice(config.PREFERRED_RESOURCES, n),
            "expected_latency_ms": np.round(rng.uniform(40, 300, n), 1),
            "expected_energy_j": np.round(rng.uniform(0.5, 6.0, n), 2),
            "attack_exposure": np.round(rng.uniform(0.0, 0.9, n), 3),
        }
        df = pd.DataFrame(data)

        # derive deterministic labels
        label = np.select(
            [
                (df["privacy_sensitivity"] > 0.7) & (df["security_sensitivity"] > 0.6),
                (df["privacy_sensitivity"] > 0.5) | (df["security_sensitivity"] > 0.5),
            ],
            ["high_risk", "sensitive"],
            default="normal",
        )
        df["label"] = label
        self.tasks = df
        self._generation_progress = 1.0

        # cleaning/validation stats for the upload animation
        valid = int(df.shape[0] * 0.998)
        self.cleaning_stats = {
            "total": int(n),
            "valid": valid,
            "invalid": int(n - valid),
            "sensitive": int((df["label"] == "sensitive").sum()),
            "high_risk": int((df["label"] == "high_risk").sum()),
        }
        return df

    def load_csv(self, path):
        """Load tasks from a CSV file generated by the dataset generator."""
        df = pd.read_csv(path)
        if "task_id" not in df.columns:
            raise ValueError("CSV is missing required 'task_id' column")
        self.tasks = df
        self.cleaning_stats = {
            "total": int(df.shape[0]),
            "valid": int(df.shape[0]),
            "invalid": 0,
            "sensitive": (
                int((df["label"] == "sensitive").sum()) if "label" in df.columns else 0
            ),
            "high_risk": (
                int((df["label"] == "high_risk").sum()) if "label" in df.columns else 0
            ),
        }
        self._generation_progress = 1.0
        return df

    # ------------------------------------------------------------------
    # Validation & processing helpers
    # ------------------------------------------------------------------
    def _task_as_dict(self, row):
        return {
            "task_id": str(row["task_id"]),
            "task_type": str(row.get("task_type", "unknown")),
            "data_size_mb": float(row.get("data_size_mb", 0.0)),
            "cpu_cycles_giga": float(row.get("cpu_cycles_giga", 0.0)),
            "memory_mb": float(row.get("memory_mb", 0.0)),
            "deadline_ms": float(row.get("deadline_ms", 0.0)),
            "privacy_sensitivity": float(row.get("privacy_sensitivity", 0.0)),
            "security_sensitivity": float(row.get("security_sensitivity", 0.0)),
            "arrival_rate": float(row.get("arrival_rate", 0.0)),
            "source_node": str(row.get("source_node", "EDGE")),
            "preferred_resource": str(row.get("preferred_resource", "MEC-1")),
            "expected_latency_ms": float(row.get("expected_latency_ms", 0.0)),
            "expected_energy_j": float(row.get("expected_energy_j", 0.0)),
            "attack_exposure": float(row.get("attack_exposure", 0.0)),
            "label": str(row.get("label", "normal")),
        }

    def task_by_id(self, task_id):
        if self.tasks is None:
            raise KeyError("No dataset loaded")
        mask = self.tasks["task_id"].astype(str) == str(task_id)
        if not mask.any():
            raise KeyError(f"Task {task_id} not found")
        row = self.tasks[mask].iloc[0]
        item = self._task_as_dict(row)
        if task_id in self.results:
            item["assigned_resource"] = self.results[task_id]["resource"]
            item["status"] = self.results[task_id]["status"]
        return item

    # ------------------------------------------------------------------
    # Pagination
    # ------------------------------------------------------------------
    def page(self, offset=0, limit=config.PAGE_SIZE, query=None):
        if self.tasks is None:
            return [], 0
        df = self.tasks
        total = int(df.shape[0])
        if query:
            df = df[df["task_id"].astype(str).str.contains(str(query), case=False)]
            total = int(df.shape[0])
        slice_df = df.iloc[offset : offset + limit]
        rows = [self._task_as_dict(row) for _, row in slice_df.iterrows()]
        for r in rows:
            if r["task_id"] in self.results:
                r["assigned_resource"] = self.results[r["task_id"]]["resource"]
                r["status"] = self.results[r["task_id"]]["status"]
        return rows, total


if __name__ == "__main__":
    tm = TaskManager()
    df = tm.generate(1000)
    print("generated:", df.shape)
    print("stats:", tm.cleaning_stats)
    print("first:", df.iloc[0].to_dict())
